/**
 * AI tutor chat (PRD 5.2). Reused by the full Tutor page and the course player's side panel.
 *
 * Flow: the first message creates a session for the course → each message is POSTed to
 * /ai/chat/sessions/:id/messages → the backend retrieves matching course passages (RAG),
 * asks Gemini (Google Vertex AI), and returns the reply plus the passages it cited ("sources").
 */
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import clsx from 'clsx';
import { ArrowUp, BookOpen, FileText, GraduationCap, Info, PlayCircle, RotateCcw, Sparkles } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import { toast } from 'sonner';
import { Markdown } from '@/components/common/Markdown';
import { Avatar, Badge, Segmented, Spinner } from '@/components/common/ui';
import { api, errMsg } from '@/services/api';
import { useAuth } from '@/store/auth';
import type { ChatMessage, Mode, Source } from '@/types';
import { clock } from '@/utils/format';

export function useAIStatus() {
  return useQuery({ queryKey: ['ai-status'], queryFn: async () => (await api.get<{ available: boolean; mode: 'live' | 'demo' | 'unavailable'; model: string | null }>('/ai/status')).data, staleTime: 60_000 });
}

export function AIModeBadge() {
  const { data } = useAIStatus();
  if (!data) return null;
  if (data.mode === 'live') return <Badge tone="success"><span className="h-1.5 w-1.5 rounded-full bg-emerald-500" /><span title={data.model ? `Google Vertex AI · ${data.model}` : 'Google Vertex AI'}>Live AI · Gemini</span></Badge>;
  if (data.mode === 'demo') return <Badge tone="warning" className="cursor-help"><Info className="h-3 w-3" /><span title="Live AI (Google Vertex AI) is not configured. Answers are assembled from the most relevant course passages and are not generated by an AI model.">Demo mode</span></Badge>;
  return <Badge tone="danger">AI unavailable</Badge>;
}

const SUGGESTIONS = [
  'Explain the main idea of this course in simple terms',
  'What are the most common mistakes students make here?',
  'Give me a worked example of the hardest concept',
  'Quiz me with 3 quick questions',
];

export function SourceChip({ s, courseId, onSeek, currentLectureId }: { s: Source; courseId: string; onSeek?: (seconds: number) => void; currentLectureId?: string }) {
  const label = (
    <>
      {s.source_type === 'transcript' ? <PlayCircle className="h-3 w-3 shrink-0" /> : <FileText className="h-3 w-3 shrink-0" />}
      <span className="truncate">[{s.index}] {s.lecture_title}{s.timestamp_seconds != null && s.source_type === 'transcript' ? ` · ${clock(s.timestamp_seconds)}` : s.source_name ? ` · ${s.source_name}` : ''}</span>
    </>
  );
  const cls = 'chip max-w-full border border-border bg-surface text-muted transition hover:border-brand-300 hover:text-brand-700 dark:hover:text-brand-300';
  if (onSeek && s.lecture_id === currentLectureId && s.timestamp_seconds != null) {
    return <button className={cls} onClick={() => onSeek(s.timestamp_seconds!)} title={s.snippet}>{label}</button>;
  }
  return <Link className={cls} to={`/app/learn/${courseId}/${s.lecture_id}${s.timestamp_seconds != null ? `?t=${s.timestamp_seconds}` : ''}`} title={s.snippet}>{label}</Link>;
}

interface Props {
  courseId: string;
  courseTitle?: string;
  sessionId?: string | null;
  lectureId?: string;
  compact?: boolean;
  onSessionCreated?: (id: string) => void;
  onSeek?: (seconds: number) => void;
}

export function ChatPanel({ courseId, courseTitle, sessionId: initialSession, lectureId, compact, onSessionCreated, onSeek }: Props) {
  const qc = useQueryClient();
  const user = useAuth((s) => s.user)!;
  const [sessionId, setSessionId] = useState<string | null>(initialSession ?? null);
  const [mode, setMode] = useState<Mode>('intermediate');
  const [input, setInput] = useState('');
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const scrollRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => { setSessionId(initialSession ?? null); if (!initialSession) setMessages([]); }, [initialSession, courseId]);

  const session = useQuery({
    queryKey: ['chat-session', sessionId],
    enabled: !!sessionId,
    queryFn: async () => (await api.get(`/ai/chat/sessions/${sessionId}`)).data as { session: { mode: Mode; course_id: string }; messages: ChatMessage[] },
  });
  const sendingRef = useRef(false);
  useEffect(() => {
    // Don't overwrite the optimistic conversation while a message is in flight.
    if (session.data && !sendingRef.current) {
      setMessages(session.data.messages);
      setMode(session.data.session.mode);
    }
  }, [session.data]);
  useEffect(() => { scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: 'smooth' }); }, [messages]);

  const changeMode = useMutation({
    mutationFn: (m: Mode) => api.put(`/ai/chat/sessions/${sessionId}/mode`, { mode: m }),
    onError: (e) => toast.error(errMsg(e)),
  });

  const send = useMutation({
    mutationFn: async (text: string) => {
      let sid = sessionId;
      if (!sid) {
        const s = (await api.post('/ai/chat/sessions', { course_id: courseId, mode })).data;
        sid = s.id as string;
        setSessionId(sid);
        setMode(s.mode);
        onSessionCreated?.(sid);
      }
      return (await api.post(`/ai/chat/sessions/${sid}/messages`, { message: text, lecture_id: lectureId })).data;
    },
    onSettled: () => { sendingRef.current = false; },
    onMutate: (text) => {
      sendingRef.current = true;
      setMessages((m) => [...m, { id: `tmp-${Date.now()}`, sender: 'user', content: text, created_at: new Date().toISOString(), pending: true }]);
      setInput('');
    },
    onSuccess: (data) => {
      setMessages((m) => [...m.filter((x) => !x.pending), data.user_message, data.message]);
      qc.invalidateQueries({ queryKey: ['chat-sessions'] });
    },
    onError: (e, text) => {
      setMessages((m) => m.filter((x) => !x.pending));
      setInput(text);
      toast.error(errMsg(e));
    },
  });

  const submit = (text = input) => {
    const t = text.trim();
    if (!t || send.isPending) return;
    send.mutate(t);
  };

  return (
    <div className={clsx('flex h-full min-h-0 flex-col', !compact && 'card overflow-hidden')}>
      <div className="flex flex-wrap items-center gap-2 border-b border-border px-4 py-3">
        <div className="flex min-w-0 items-center gap-2">
          <div className="grid h-8 w-8 shrink-0 place-items-center rounded-xl bg-gradient-to-br from-brand-500 to-brand-700 text-white"><Sparkles className="h-4 w-4" /></div>
          <div className="min-w-0">
            <p className="truncate text-sm font-semibold">AI Tutor</p>
            {courseTitle && <p className="truncate text-xs text-muted">{courseTitle}</p>}
          </div>
        </div>
        <div className="ml-auto flex items-center gap-2"><AIModeBadge /></div>
        <div className="flex w-full items-center justify-between gap-2">
          <span className="text-xs text-muted">Explanation level</span>
          <Segmented size="sm" value={mode} onChange={(m) => { setMode(m); if (sessionId) changeMode.mutate(m); }}
            options={[{ value: 'beginner', label: 'Beginner' }, { value: 'intermediate', label: 'Intermediate' }, { value: 'advanced', label: 'Advanced' }]} />
        </div>
      </div>

      <div ref={scrollRef} className="flex-1 space-y-5 overflow-y-auto px-4 py-5 scrollbar-thin" aria-live="polite">
        {session.isLoading && sessionId ? <div className="flex justify-center py-10"><Spinner /></div> : !messages.length ? (
          <div className="flex h-full flex-col items-center justify-center py-6 text-center">
            <div className="mb-4 grid h-14 w-14 place-items-center rounded-2xl bg-brand-50 text-brand-600 dark:bg-brand-500/15 dark:text-brand-300"><GraduationCap className="h-7 w-7" /></div>
            <p className="font-semibold">Ask anything about this course</p>
            <p className="mt-1 max-w-sm text-sm text-muted">Answers come from the course's lectures and documents, with citations you can click to jump to the source.</p>
            <div className={clsx('mt-5 grid w-full gap-2', !compact && 'sm:grid-cols-2')}>
              {SUGGESTIONS.slice(0, compact ? 3 : 4).map((s) => (
                <button key={s} onClick={() => submit(s)} className="rounded-xl border border-border bg-surface px-3 py-2.5 text-left text-sm transition hover:border-brand-300 hover:bg-brand-50/40 dark:hover:bg-brand-500/10">{s}</button>
              ))}
            </div>
          </div>
        ) : messages.map((m) => (
          <div key={m.id} className={clsx('flex gap-3 animate-fade-in', m.sender === 'user' && 'flex-row-reverse')}>
            {m.sender === 'user' ? <Avatar name={user.full_name} src={user.avatar_url} size={30} /> : <div className="grid h-[30px] w-[30px] shrink-0 place-items-center rounded-full bg-gradient-to-br from-brand-500 to-brand-700 text-white"><Sparkles className="h-3.5 w-3.5" /></div>}
            <div className={clsx('min-w-0 max-w-[85%]', m.sender === 'user' && 'text-right')}>
              <div className={clsx('inline-block rounded-2xl px-4 py-2.5 text-left', m.sender === 'user' ? 'rounded-tr-md bg-brand-600 text-white' : 'rounded-tl-md bg-surface-2')}>
                {m.sender === 'user' ? <p className="whitespace-pre-wrap text-[0.925rem]">{m.content}</p> : <Markdown>{m.content}</Markdown>}
              </div>
              {m.sender === 'ai' && (
                <div className="mt-2 space-y-1.5">
                  {m.is_demo && <Badge tone="warning">Demo response — assembled from course passages, not AI-generated</Badge>}
                  {!!m.sources?.length && (
                    <div className="flex flex-wrap gap-1.5"><span className="flex items-center gap-1 text-xs text-muted"><BookOpen className="h-3 w-3" />Sources:</span>{m.sources.map((s) => <SourceChip key={s.index} s={s} courseId={courseId} onSeek={onSeek} currentLectureId={lectureId} />)}</div>
                  )}
                </div>
              )}
            </div>
          </div>
        ))}
        {send.isPending && (
          <div className="flex gap-3">
            <div className="grid h-[30px] w-[30px] shrink-0 place-items-center rounded-full bg-gradient-to-br from-brand-500 to-brand-700 text-white"><Sparkles className="h-3.5 w-3.5" /></div>
            <div className="flex items-center gap-1 rounded-2xl rounded-tl-md bg-surface-2 px-4 py-3" aria-label="AI tutor is typing">
              {[0, 1, 2].map((i) => <span key={i} className="h-2 w-2 animate-bounce3 rounded-full bg-brand-500" style={{ animationDelay: `${i * 0.16}s` }} />)}
              <span className="ml-2 text-xs text-muted">Searching course material…</span>
            </div>
          </div>
        )}
      </div>

      <form onSubmit={(e) => { e.preventDefault(); submit(); }} className="border-t border-border p-3">
        <div className="flex items-end gap-2 rounded-2xl border border-border bg-surface p-2 transition focus-within:border-brand-500 focus-within:ring-4 focus-within:ring-brand-500/15">
          <textarea ref={inputRef} value={input} onChange={(e) => setInput(e.target.value)} rows={1}
            onKeyDown={(e) => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); submit(); } }}
            placeholder="Ask a question about the course…" aria-label="Message the AI tutor" maxLength={4000}
            className="max-h-40 min-h-[40px] flex-1 resize-none bg-transparent px-2 py-2 text-sm outline-none placeholder:text-muted/70" />
          <button type="submit" disabled={!input.trim() || send.isPending} className="grid h-10 w-10 shrink-0 place-items-center rounded-xl bg-brand-600 text-white transition hover:bg-brand-700 disabled:opacity-40" aria-label="Send">
            {send.isPending ? <Spinner className="h-4 w-4 text-white" /> : <ArrowUp className="h-4 w-4" />}
          </button>
        </div>
        <div className="mt-1.5 flex items-center justify-between px-1 text-[11px] text-muted">
          <span>Enter to send · Shift+Enter for a new line</span>
          {messages.length > 0 && <button type="button" onClick={() => { setSessionId(null); setMessages([]); onSessionCreated?.(''); }} className="flex items-center gap-1 hover:text-ink"><RotateCcw className="h-3 w-3" />New chat</button>}
        </div>
      </form>
    </div>
  );
}
