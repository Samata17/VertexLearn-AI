"""
DEMO MODE — used when Vertex AI is not configured (no GOOGLE_CLOUD_PROJECT or no credentials), and as a
labelled fallback for chat / summaries / study plans when Vertex AI fails after its retries.

Nothing here is generated by an AI model. Retrieval (pgvector search) is still real, and the
outputs are built with simple text analysis (keyword frequency, sentence extraction) over the
actual course material. Every response from this module carries `is_demo: True`, and the UI
shows a "Demo mode" label, so demo output is never presented as a live AI answer.
"""
from __future__ import annotations

import random
import re
from collections import Counter

from app.rag.chunking import split_sentences

DEMO_NOTICE = (
    "**Demo mode** - live AI (Google Vertex AI) is not configured or is temporarily unavailable, so this was "
    "assembled from the course passages that best match your request, not written by an AI model."
)

STOPWORDS = set(
    """a about above after again against all also am an and any are as at be because been before being below
    between both but by can could did do does doing down during each few for from further had has have having he
    her here hers him his how i if in into is it its itself just let like make many may me more most much must my
    no nor not now of off on once one only or other our out over own same she should so some such than that the
    their them then there these they this those through to too two under until up us use used using very was we
    were what when where which while who whom why will with would you your yours really thing things way get gets
    going know see say said want lot okay right well first second next called different important example
    instance means mean let's we're it's that's here's there's you'll we'll can't don't""".split()
)


def keywords(text: str, n: int = 12) -> list[str]:
    words = re.findall(r"[A-Za-z][A-Za-z\-]{3,}", text)
    counts = Counter(w.lower() for w in words if w.lower() not in STOPWORDS)
    # Prefer two-word phrases that repeat ("binary search", "pivot element")
    tokens = [w.lower() for w in re.findall(r"[A-Za-z][A-Za-z\-]+", text)]
    bigrams = Counter(
        f"{a} {b}" for a, b in zip(tokens, tokens[1:]) if a not in STOPWORDS and b not in STOPWORDS and len(a) > 2 and len(b) > 2
    )
    phrases = [p for p, c in bigrams.most_common(n) if c >= 2]
    singles = [w for w, _ in counts.most_common(n * 2) if not any(w in p for p in phrases)]
    return (phrases + singles)[:n]


def top_sentences(text: str, n: int = 5) -> list[str]:
    sentences = [s for s in split_sentences(text) if 40 <= len(s) <= 320]
    if not sentences:
        return []
    kw = set(" ".join(keywords(text, 20)).split())
    scored = [(sum(1 for w in re.findall(r"[a-z\-]+", s.lower()) if w in kw), i, s) for i, s in enumerate(sentences)]
    best = sorted(scored, key=lambda t: (-t[0], t[1]))[:n]
    return [s for _, _, s in sorted(best, key=lambda t: t[1])]


def chat(question: str, chunks: list[dict], mode: str) -> str:
    if not chunks:
        return (
            f"{DEMO_NOTICE}\n\nI couldn't find anything about this in the course material. "
            "Try rephrasing your question, or ask your instructor in the course discussion forum."
        )
    lead = {
        "beginner": "Here are the parts of your course that explain this, in the order they appear:",
        "intermediate": "These course passages answer your question most directly:",
        "advanced": "The most relevant technical passages from the course material:",
    }.get(mode, "These course passages are most relevant:")
    lines = [DEMO_NOTICE, "", lead, ""]
    for i, c in enumerate(chunks[:3], 1):
        sents = split_sentences(c["chunk_text"])
        excerpt = " ".join(sents[:3]) if mode != "advanced" else " ".join(sents[:5])
        lines.append(f"- **{c['lecture_title']}** - {excerpt} [{i}]")
    lines += ["", "_With live AI (Vertex AI) switched on, you'd get an explanation written for your level._"]
    return "\n".join(lines)


def summarize(text: str, title: str) -> dict:
    points = top_sentences(text, 6)
    sents = split_sentences(text)
    terms = keywords(text, 6)
    defs = []
    for t in terms:
        s = next((s for s in sents if t in s.lower() and 30 < len(s) < 300), None)
        if s:
            defs.append({"term": t.title(), "definition": s})
    return {
        "summary": f"{DEMO_NOTICE} This lecture, \"{title}\", focuses on {', '.join(terms[:4]) or 'the topics below'}. "
        + (" ".join(sents[:2]) if sents else ""),
        "key_points": points,
        "key_terms": defs[:5],
    }


def quiz(text: str, n: int) -> list[dict]:
    """Fill-in-the-blank questions built from real sentences of the lecture."""
    sents = [s for s in split_sentences(text) if 50 <= len(s) <= 260]
    terms = [t for t in keywords(text, 24) if len(t) > 3]
    rng = random.Random(len(text))
    questions: list[dict] = []
    used: set[str] = set()
    for term in terms:
        if len(questions) >= n:
            break
        s = next((s for s in sents if re.search(rf"\b{re.escape(term)}\b", s, re.I) and s not in used), None)
        if not s:
            continue
        used.add(s)
        blanked = re.sub(rf"\b{re.escape(term)}\b", "_____", s, count=1, flags=re.I)
        if len(questions) % 4 == 3:
            questions.append({
                "question_text": f"[Demo] Fill in the blank: \"{blanked}\"",
                "question_type": "short_answer",
                "explanation": f"From the lecture: \"{s}\"",
                "options": [{"option_text": term, "is_correct": True}],
            })
            continue
        distractors = [t for t in terms if t != term and t not in term and term not in t]
        rng.shuffle(distractors)
        opts = [{"option_text": term, "is_correct": True}] + [{"option_text": d, "is_correct": False} for d in distractors[:3]]
        rng.shuffle(opts)
        questions.append({
            "question_text": f"[Demo] Which term completes this statement from the lecture? \"{blanked}\"",
            "question_type": "mcq",
            "explanation": f"From the lecture: \"{s}\"",
            "options": opts,
        })
    return questions


def flashcards(text: str, n: int) -> list[dict]:
    sents = split_sentences(text)
    cards = []
    for t in keywords(text, n * 2):
        s = next((s for s in sents if t in s.lower() and 30 < len(s) < 300), None)
        if s:
            cards.append({"question": f"[Demo] What does the course say about \"{t}\"?", "answer": s})
        if len(cards) >= n:
            break
    return cards


def study_plan(course_title: str, modules: list[dict], weeks: int, hours_per_week: int) -> dict:
    """Rule-based plan: weakest / unfinished modules first, spread over the available weeks."""
    def priority(m: dict) -> float:
        mastery = m.get("mastery")
        unfinished = sum(1 for l in m.get("lectures", []) if not l.get("completed"))
        return (mastery if mastery is not None else 50) - unfinished * 5

    ordered = sorted(modules, key=priority)
    minutes_per_week = hours_per_week * 60
    plan_weeks = []
    queue = []
    for m in ordered:
        for l in m.get("lectures", []):
            if not l.get("completed"):
                queue.append({"title": f"Watch: {l['title']}", "type": "watch", "lecture_id": l["id"], "minutes": max(10, (l.get("duration_seconds") or 900) // 60 + 5), "module": m["title"]})
        if m.get("mastery") is not None and m["mastery"] < 70:
            queue.append({"title": f"Review notes and retake the quiz for {m['title']}", "type": "quiz", "lecture_id": "", "minutes": 30, "module": m["title"]})
            queue.append({"title": f"Ask the AI tutor about the parts of {m['title']} you find hardest", "type": "ask_tutor", "lecture_id": "", "minutes": 15, "module": m["title"]})
    if not queue:
        queue = [{"title": f"Revise {m['title']} with flashcards", "type": "review", "lecture_id": "", "minutes": 20, "module": m["title"]} for m in ordered]
    for w in range(1, weeks + 1):
        tasks, used = [], 0
        while queue and used + queue[0]["minutes"] <= minutes_per_week:
            t = queue.pop(0)
            used += t["minutes"]
            tasks.append({k: t[k] for k in ("title", "type", "lecture_id", "minutes")})
        if not tasks and queue:
            t = queue.pop(0)
            tasks.append({k: t[k] for k in ("title", "type", "lecture_id", "minutes")})
        plan_weeks.append({
            "week": w,
            "focus": tasks[0]["title"].split(": ", 1)[-1] if tasks else "Consolidation and revision",
            "goals": [f"Complete {len(tasks)} planned activities"] if tasks else ["Revise weak topics with flashcards and quizzes"],
            "tasks": tasks,
        })
    weakest = [m["title"] for m in ordered if m.get("mastery") is not None and m["mastery"] < 70][:3]
    return {
        "overview": f"{DEMO_NOTICE} This rule-based plan for \"{course_title}\" puts your weakest and unfinished modules first"
        + (f" (starting with {', '.join(weakest)})" if weakest else "")
        + f", at about {hours_per_week} hours per week.",
        "weekly_hours": hours_per_week,
        "weeks": plan_weeks,
        "tips": [
            "Study in focused 25-minute blocks with short breaks.",
            "Retake a module's quiz after reviewing it - mastery updates automatically.",
            "Use bookmarks to mark confusing moments, then ask the tutor about them.",
        ],
    }
